    private static final Map<String, String> BY_LOWER_CASE = new HashMap<>();

    static {
        for (String title : ASTRO_TITLES) BY_LOWER_CASE.put(title.toLowerCase(), title);
        for (String title : OTHER_TITLES) BY_LOWER_CASE.putIfAbsent(title.toLowerCase(), title);
    }

    /** the title's real spelling, or the name as given when it is not a known title */
    public static String getTitle(String name) {
        return BY_LOWER_CASE.getOrDefault(name.toLowerCase(), name);
    }
